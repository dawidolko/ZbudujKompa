/**
 * Configures the chat assistant's optional remote provider.
 *
 *   node .tools/scripts/setup-chat-key.mjs <API_KEY> [provider]
 *
 * Writes .env.local, which is gitignored — the key never reaches the
 * repository. Restart the dev server afterwards, because Next.js reads
 * NEXT_PUBLIC_* variables at build time rather than per request.
 *
 * The key is verified against the provider before anything is written, so a
 * typo or an expired key is reported here rather than showing up later as an
 * assistant that silently falls back to local answers.
 */

import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/** Providers with a usable free tier, and the model to default to on each. */
const PROVIDERS = {
  groq: {
    url: 'https://api.groq.com/openai/v1/chat/completions',
    model: 'llama-3.3-70b-versatile',
    keysAt: 'https://console.groq.com/keys',
    prefix: 'gsk_',
  },
  openrouter: {
    url: 'https://openrouter.ai/api/v1/chat/completions',
    model: 'meta-llama/llama-3.3-70b-instruct:free',
    keysAt: 'https://openrouter.ai/keys',
    prefix: 'sk-or-',
  },
  cerebras: {
    url: 'https://api.cerebras.ai/v1/chat/completions',
    model: 'llama-3.3-70b',
    keysAt: 'https://cloud.cerebras.ai',
    prefix: 'csk-',
  },
};

const [key, providerName = 'groq'] = process.argv.slice(2);

if (!key) {
  console.error('Usage: node .tools/scripts/setup-chat-key.mjs <API_KEY> [provider]\n');
  console.error('Providers with a free tier:');
  for (const [name, config] of Object.entries(PROVIDERS)) {
    console.error(`  ${name.padEnd(12)} keys at ${config.keysAt}`);
  }
  process.exit(1);
}

const provider = PROVIDERS[providerName];
if (!provider) {
  console.error(`Unknown provider "${providerName}".`);
  console.error(`Known: ${Object.keys(PROVIDERS).join(', ')}`);
  process.exit(1);
}

/* A wrong-provider key is a common mistake and produces a confusing 401 much
   later, so flag the mismatch up front rather than failing at request time. */
if (provider.prefix && !key.startsWith(provider.prefix)) {
  console.warn(
    `Warning: ${providerName} keys usually start with "${provider.prefix}", but this one does not.`,
  );
  console.warn('Continuing anyway — the live check below is what actually decides.\n');
}

console.log(`Checking the key against ${providerName}…`);

const response = await fetch(provider.url, {
  method: 'POST',
  headers: {
    'Content-Type': 'application/json',
    Authorization: `Bearer ${key}`,
  },
  body: JSON.stringify({
    model: provider.model,
    max_tokens: 8,
    messages: [{ role: 'user', content: 'ping' }],
  }),
}).catch((error) => {
  console.error(`Could not reach ${providerName}: ${error.message}`);
  process.exit(1);
});

if (!response.ok) {
  const detail = await response.text().catch(() => '');
  console.error(`\n${providerName} rejected the key (HTTP ${response.status}).`);
  if (response.status === 401) console.error('That usually means the key is wrong or revoked.');
  if (response.status === 429) console.error('That is a rate limit — the key itself may be fine.');
  if (detail) console.error(detail.slice(0, 300));
  process.exit(1);
}

console.log('Key accepted.\n');

const envPath = join(process.cwd(), '.env.local');

await writeFile(
  envPath,
  `# Local development configuration.
# Gitignored — this file must never be committed.
# Generated by .tools/scripts/setup-chat-key.mjs

NEXT_PUBLIC_SITE_URL=http://localhost:3000
NEXT_PUBLIC_BASE_PATH=

NEXT_PUBLIC_CHAT_API_URL=${provider.url}
NEXT_PUBLIC_CHAT_API_KEY=${key}
NEXT_PUBLIC_CHAT_MODEL=${provider.model}
`,
  'utf8',
);

console.log(`Wrote .env.local for ${providerName} (${provider.model}).`);
console.log('\nRestart the dev server to pick it up:');
console.log('  npm run dev');
console.log('\nFor the deployed site, add the same three values as repository');
console.log('secrets and reference them in .github/workflows/deploy.yml.');
console.log('\nReminder: a key compiled into a static build is readable by anyone');
console.log('who opens the bundle. Keep a spending limit on it.');
